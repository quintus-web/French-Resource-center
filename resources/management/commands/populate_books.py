class Command(BaseCommand):
    help = 'Populate the database with the initial book catalogue'

    def handle(self, *args, **kwargs):
        created_resources = 0
        created_copies = 0
        skipped = 0

        for title, author, year, publisher, series, copy_no, accompany, accession in BOOKS:
            category = get_category(title, series)
            level = get_level(series)

            publisher_obj = None
            if publisher:
                publisher_obj, _ = Publisher.objects.get_or_create(name=publisher)

            resource, resource_created = Resource.objects.get_or_create(
                title=title,
                defaults={
                    'publisher': publisher_obj,
                    'publication_year': year,
                    'level': level,
                    'category': category,
                }
            )
            if resource_created:
                created_resources += 1

            # Legacy catalogue rows store multiple authors in one comma-separated field.
            for author_name in (author or '').replace(' et ', ', ').split(','):
                author_name = author_name.strip()
                if not author_name:
                    continue
                parts = author_name.rsplit(' ', 1)
                first_name, last_name = (parts if len(parts) == 2 else ('', parts[0]))
                author_obj, _ = Author.objects.get_or_create(
                    first_name=first_name, last_name=last_name
                )
                resource.authors.add(author_obj)

            notes = ''
            if accompany:
                notes = accompany
            if series and copy_no:
                notes = f"Vol/Series: {series}, Copy: {copy_no}" + (f" | {accompany}" if accompany else '')
            elif series:
                notes = f"Vol/Series: {series}" + (f" | {accompany}" if accompany else '')
            elif copy_no:
                notes = f"Copy: {copy_no}" + (f" | {accompany}" if accompany else '')

            _, copy_created = BookCopy.objects.get_or_create(
                accession_number=accession,
                defaults={
                    'resource': resource,
                    'status': 'AVAILABLE',
                    'notes': notes,
                }
            )
            if copy_created:
                created_copies += 1
            else:
                skipped += 1

        self.stdout.write(self.style.SUCCESS(
            f'Done. Resources created: {created_resources} | Copies created: {created_copies} | Skipped (duplicate accession): {skipped}'
        ))
