def get_category(title, series):
    t = title.upper()
    s = (series or '').upper()
    if any(x in t for x in ['ASTERIX', 'SPIROU', 'PIRATE', 'PICOU', 'TINTIN', 'THORGAL', 'CACTUS']):
        return 'COMIC'
    if any(x in t for x in ['DELF', 'DALF', 'ABC DELF', '100 DELF']):
        return 'DELF'
    if 'DELF' in s or 'DALF' in s:
        return 'DELF'
    if any(x in t for x in ['DICTIONNAIRE', 'DICTIONNAIRES', 'LAROUSSE', 'BESCHERELLE', 'HARRAR']):
        return 'DICTIONARY'
    if any(x in t for x in ['GRAMMAIRE', 'VOCABULAIRE', 'CONJUGAISON', 'ORTHOGRAPHE', 'PHONETIQUE']):
        return 'GRAMMAR'
    if any(x in t for x in ['MAGAZINE', 'REVUE', 'ATLAS', 'CAHIERS']):
        return 'MAGAZINE'
    return 'NOVEL'


def get_level(series):
    s = (series or '').upper()
    if 'A1' in s:
        return 'A1'
    if 'A2' in s:
        return 'A2'
    if 'B1' in s:
        return 'B1'
    if 'B2' in s:
        return 'B2'
    if 'C1' in s:
        return 'C1'
    return 'GEN'


